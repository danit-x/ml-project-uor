"""Regenerate the progress-evaluation results tables from reports/ (no hand-typed numbers).

    python docs/progress_evaluation/results_tables.py      # writes docs/progress_evaluation/results_tables.md

Reads the full-data outputs of `python main.py` and `python tune_models.py`:
reports/official_comparison.csv, results.csv, cv_results.csv, format_baseline.csv,
format_controlled.csv, risk_bands.csv and reports/tuning/*.csv.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from src import config  # noqa: E402

R = config.RESULTS_DIR
OUT = Path(__file__).with_name("results_tables.md")


def md(frame: pd.DataFrame, digits=4) -> str:
    """Markdown table without extra dependencies (pandas.to_markdown needs tabulate)."""
    frame = frame.copy()
    for col in frame.columns:
        if pd.api.types.is_float_dtype(frame[col]):
            frame[col] = frame[col].map(lambda v: "" if pd.isna(v) else f"{v:.{digits}f}")
    head = "| " + " | ".join(map(str, frame.columns)) + " |"
    sep = "|" + "|".join("---" for _ in frame.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in frame.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def official():
    o = pd.read_csv(R / "official_comparison.csv")
    cv = o[["model"]].assign(**{
        f"CV {m}": o[f"cv_{m}_mean"].map(lambda v: f"{v:.4f}") + " ± " + o[f"cv_{m}_std"].map(lambda v: f"{v:.4f}")
        for m in ("f1", "roc_auc", "precision", "recall", "accuracy")})
    test = o[["model", "test_accuracy", "test_precision", "test_recall", "test_f1", "test_roc_auc",
              "test_tn", "test_fp", "test_fn", "test_tp", "test_brier"]]
    test.columns = ["model", "accuracy", "precision", "recall", "F1", "ROC-AUC", "TN", "FP", "FN", "TP", "Brier"]
    return cv, test


def baseline():
    b = pd.read_csv(R / "format_baseline.csv").iloc[0]
    row = {"reference": b["reference"],
           "CV F1": f"{b['cv_f1_mean']:.4f} ± {b['cv_f1_std']:.4f}",
           "test accuracy": b["test_accuracy"], "test precision": b["test_precision"],
           "test recall": b["test_recall"], "test F1": b["test_f1"],
           "TN": int(b["test_tn"]), "FP": int(b["test_fp"]), "FN": int(b["test_fn"]), "TP": int(b["test_tp"]),
           "legit bare share (train)": b["share_legitimate_bare_train"],
           "phishing bare share (train)": b["share_phishing_bare_train"]}
    return pd.DataFrame([row])


def secondary():
    res = pd.read_csv(R / "results.csv")
    keep = ["feature_set", "model", "protocol", "n_features", "f1", "roc_auc", "precision", "recall", "fp", "fn"]
    return res[keep]


def cv_sets():
    cv = pd.read_csv(R / "cv_results.csv")
    piv = cv.pivot(index="model", columns="feature_set", values="f1_mean")
    piv = piv[["url_base", "url_engineered", "extended"]].reset_index()
    piv["engineered − base"] = piv["url_engineered"] - piv["url_base"]
    return piv


def main():
    parts = ["# Results tables (generated)\n",
             f"Generated by `docs/progress_evaluation/results_tables.py` from `{R.name}/`. Do not edit by hand.\n"]
    cv, test = official()
    parts += ["## Official comparison: grouped 5-fold CV on 188,297 training rows (mean ± std over folds)\n",
              md(cv), "",
              "## Official comparison: held-out test (47,073 rows, frozen models, used once)\n",
              md(test), ""]
    parts += ["## Format reference rule (no learning) on the same CV folds and test rows\n", md(baseline()), ""]
    fc = pd.read_csv(R / "format_controlled.csv")
    parts += ["## Format-controlled held-out breakdown (diagnostic)\n", md(fc), ""]
    parts += ["## Grouped CV F1 by feature set (secondary comparison)\n", md(cv_sets()), ""]
    parts += ["## Held-out results, all models and feature sets\n", md(secondary()), ""]
    parts += ["## Risk bands, calibrated Random Forest, held-out test\n",
              md(pd.read_csv(R / "risk_bands.csv")), ""]
    shap = R / "shap_importance.csv"
    if shap.exists():
        parts += ["## Mean |SHAP| (Random Forest, first 500 held-out URLs)\n",
                  md(pd.read_csv(shap).head(10)), ""]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
